#!/usr/bin/env python3
"""Reproducible source/contract inventory with direct-reference and family evidence.

Direct lexical references are navigation aids, not a claim of branch or contract coverage.
The report supplies the executed family probes and their semantic boundaries.
"""
import argparse
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / '.code-arena/oss-comparison/2026-10-26-followthrough'
DECLARATION = re.compile(r'\b(?:public|internal)\s+(?:(?:sealed|static|abstract|partial|readonly|ref)\s+)*'
                         r'(?:class|interface|enum|struct|record(?:\s+(?:class|struct))?)\s+(\w+)')
AREAS = {
    'io': ['AppendOnlyFileStorage', 'LogSegmentFileStorage', 'LsmTree', 'SortedStringTable', 'ValueLog', 'WriteAheadLog'],
    'columnar': ['TimeSeries', 'Schemas', 'Serialization', 'Compression'],
    'distributed': ['Cdc', 'Events', 'ObjectStore'],
    'algorithms-query': ['Algorithms', 'Analytics', 'Batch', 'Caching', 'DataStructures', 'Indexing', 'KeyValueStore',
                         'Search', 'StorageWithBloomFilter', 'Streaming'],
}


def family(path):
    parts = path.parts
    if parts[1] == 'Distributed':
        return 'distributed', '/'.join(parts[1:3])
    if parts[1].startswith('SourceGenerator'):
        return 'columnar', parts[1]
    for owner, names in AREAS.items():
        if any(name in parts[2:] for name in names):
            return owner, '/'.join(parts[1:3])
    return 'shared-contract', '/'.join(parts[1:3])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results-directory', type=Path, default=DEST / 'final-tests')
    results_directory = parser.parse_args().results_directory.resolve()
    tests = {str(p.relative_to(ROOT)): set(re.findall(r'\b\w+\b', p.read_text())) for p in (ROOT / 'tests').rglob('*.cs')
             if not {'obj', 'bin'}.intersection(p.parts)}
    rows = []
    executed = set()
    for result in results_directory.glob('*.trx'):
        tree = ET.parse(result)
        for item in tree.iter():
            if item.tag.endswith('UnitTestResult') and item.get('outcome') == 'Passed':
                executed.add(item.get('testName', ''))
    executed_by_file = {test: {name for name in executed if f'.{Path(test).stem}.' in name}
                        for test in tests}
    for project in ['Domain', 'Infrastructure', 'Distributed', 'SourceGenerator', 'SourceGenerator.CodeFixes']:
        for source in sorted((ROOT / 'src' / project).rglob('*.cs')):
            if {'obj', 'bin'}.intersection(source.parts):
                continue
            path = source.relative_to(ROOT)
            declarations = sorted(set(DECLARATION.findall(source.read_text())))
            owner, area = family(path)
            direct = sorted(name for name, content in tests.items()
                            if set(declarations).intersection(content))
            rows.append(dict(source=str(path), package=('source-only' if project == 'Distributed' else
                             'analyzer' if project.startswith('SourceGenerator') else 'runtime'),
                             family=area, owner=owner, declarations=declarations,
                             direct_test_references=direct,
                             evidence_kind='direct references plus family integration' if direct else 'family integration/supporting source'))
            # Match the test class filename to fully-qualified executed test names. This is
            # deliberately a navigation metric, not instrumented production-code coverage.
            rows[-1]['executed_test_count_from_direct_files'] = len(
                set().union(*(executed_by_file[test] for test in direct)))
            rows[-1]['execution_scope'] = (str(results_directory.relative_to(ROOT)) if executed
                                           else 'pending final integrated suites')
    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / 'source-inventory.json').write_text(json.dumps(rows, indent=2) + '\n')
    lines = ['# Whole-library source and contract inventory', '',
             'Generated by `python3 scripts/inventory-storage-contracts.py`. Includes Domain, Infrastructure,',
             'source-only Distributed, generator and bundled code fixes; excludes samples/benchmarks and build outputs.',
             'Public API snapshots and analyzer release files remain the canonical individual member inventories.',
             'Direct test references are lexical links, not measured branch coverage. Supporting source rows are',
             'accounted through their family integration tests; the family reports state independent probes and limits.', '',
             '| Source | Family | Surface | Direct test files | Evidence kind |',
             '|---|---|---|---:|---|']
    lines.extend(f"| {r['source']} | {r['family']} | {r['package']} | {len(r['direct_test_references'])} | {r['evidence_kind']} |" for r in rows)
    (DEST / 'source-inventory.md').write_text('\n'.join(lines) + '\n')
    print(f'{len(rows)} source rows; {sum(bool(r["direct_test_references"]) for r in rows)} have direct lexical test references')


if __name__ == '__main__':
    main()
