namespace Boutquin.Storage.SourceGenerator;

/// <summary>
/// Emits the partial-type extension carrying a static <c>ColumnarFieldPlan</c> property for
/// each <see cref="ColumnarSourceGenerator.ColumnarTypePlan"/>.
/// </summary>
internal static class ColumnarCodeGenerator
{
    public static string Generate(ColumnarSourceGenerator.ColumnarTypePlan plan)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // No `using` directives: every emitted type reference is fully global::-qualified, matching
        // the other emitters (CodeGenerator / OrderedCodeGenerator / TaggedWireEmitter). Relying on
        // `using` directives leaves the generated file vulnerable to alias or global-using shadowing
        // in the consumer assembly — a consumer-defined `Array` or `ColumnEncoding` alias could
        // silently retarget an emitted reference.

        if (plan.Namespace is not null)
        {
            sb.Append("namespace ").Append(plan.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        // A nested target is extended inside each re-opened containing partial (outermost first),
        // as CodeGenerator does; emitting it under the namespace would declare a new top-level type.
        var parentDepth = 0;
        foreach (var parent in plan.ParentTypes)
        {
            CodeGenerator.AppendParentOpen(sb, parent, new string(' ', parentDepth * 4));
            parentDepth++;
        }

        var indent = new string(' ', parentDepth * 4);

        // Type-name positions (declaration name + every TSelf generic argument) must be escaped so
        // a record named with a verbatim C# keyword still emits compilable code.
        var typeName = IdentifierEscaper.Escape(plan.Name);

        sb.Append(indent)
          .Append(plan.Accessibility)
          .Append(" partial ")
          .Append(plan.TypeKeyword)
          .Append(' ')
          .Append(typeName);

        // Build the base list for this partial. Partial-type base lists are unioned by the
        // compiler so we only need to declare the interfaces the generator owns.
        var hasBaseList = false;
        if (!plan.SkipProjectable)
        {
            sb.Append(" : global::Boutquin.Storage.Domain.Interfaces.IProjectable<")
              .Append(typeName)
              .Append('>');
            hasBaseList = true;
        }

        if (!plan.SkipRehydratable)
        {
            sb.Append(hasBaseList ? ", " : " : ")
              .Append("global::Boutquin.Storage.Domain.Interfaces.TimeSeries.Columnar.IColumnarRehydratable<")
              .Append(typeName)
              .Append('>');
        }

        sb.AppendLine();
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).AppendLine("    /// <summary>");
        sb.Append(indent).AppendLine("    /// Source-generator-emitted per-field columnar encoding plan, keyed by property name");
        sb.Append(indent).AppendLine("    /// and carrying the <see cref=\"global::Boutquin.Storage.Domain.Enums.ColumnEncoding\"/> the Phase-5 columnar segment format");
        sb.Append(indent).AppendLine("    /// must route each column to. Populated from type-based defaults and");
        sb.Append(indent).AppendLine("    /// <c>[ColumnEncoding]</c> property overrides.");
        sb.Append(indent).AppendLine("    /// </summary>");
        sb.Append(indent).AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.Columnar.ColumnarFieldDescriptor> ColumnarFieldPlan { get; } =");
        sb.Append(indent).AppendLine("        new global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.Columnar.ColumnarFieldDescriptor[]");
        sb.Append(indent).AppendLine("        {");
        foreach (var field in plan.Fields)
        {
            sb.Append(indent)
              .Append("            new global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.Columnar.ColumnarFieldDescriptor(\"")
              .Append(field.PropertyName)
              .Append("\", global::Boutquin.Storage.Domain.Enums.ColumnEncoding.")
              .Append(field.EncodingEnumMemberName)
              .AppendLine("),");
        }
        sb.Append(indent).AppendLine("        };");

        // IProjectable<TSelf>.ProjectTo emission (parity with StorageSourceGenerator). The seed
        // differs by shape: a record struct is zero-initialised via default(T); a record class
        // uses its parameterless constructor when it has one, otherwise a constructor-free clone
        // (see AppendProjectTo / AppendRehydrate).
        if (!plan.SkipProjectable)
        {
            AppendProjectTo(sb, plan, indent);
        }

        if (!plan.SkipRehydratable)
        {
            AppendRehydrate(sb, plan, indent);
        }

        // Emit the IComparer<TSelf> factory whenever at least one public property is
        // sortable. The columnar segment format discovers this static method via cached
        // reflection and uses it instead of the legacy compiled-lambda + PropertyInfo path on
        // [ColumnarStorable] records. Skipped when the user already declares the same static
        // method on their partial.
        if (!plan.SkipSortComparer && plan.SortableProperties.Length > 0)
        {
            AppendCreateColumnSortComparer(sb, plan, indent);
        }

        sb.Append(indent).AppendLine("}");

        // Close the containing-type wrappers, innermost first.
        for (var i = parentDepth - 1; i >= 0; i--)
        {
            sb.Append(' ', i * 4).AppendLine("}");
        }

        // Keep generated text, checksums and syntax spans identical across build hosts.
        return sb.ToString().Replace("\r\n", "\n");
    }

    // ` { A = default!, B = default! }` for the required members a `new T(...)` seed must set
    // (CS9035 otherwise); empty when there are none or the seed constructor sets them itself.
    private static string RequiredMemberInitializer(ColumnarSourceGenerator.ColumnarTypePlan plan) =>
        plan.RequiredMembersToSeed.Length == 0
            ? ""
            : " { " + string.Join(", ", plan.RequiredMembersToSeed.Select(m => IdentifierEscaper.Escape(m) + " = default!")) + " }";

    private static void AppendRehydrate(StringBuilder sb, ColumnarSourceGenerator.ColumnarTypePlan plan, string indent)
    {
        var typeName = IdentifierEscaper.Escape(plan.Name);
        var isRecordStruct = plan.TypeKeyword == "record struct";
        var fieldTypes = plan.Fields.ToDictionary(f => f.PropertyName, f => f.ClrArrayTypeName, StringComparer.Ordinal);

        // Rehydrate is static, so a record class without a parameterless constructor cannot be
        // seeded by cloning `this`; call its matching constructor (a positional record's primary
        // constructor) with each matched argument read from its column, `default!` otherwise.
        string SeedArgument(string column) => column.Length == 0
            ? "default!"
            : $"columns.TryGetValue(\"{column}\", out var __seed{column}) ? (({fieldTypes[column]})__seed{column})[rowIndex] : default!";
        var initExpression = isRecordStruct
            ? $"default({typeName})"
            : plan.HasParameterlessConstructor
                ? $"new {typeName}(){RequiredMemberInitializer(plan)}"
                : $"new {typeName}({string.Join(", ", plan.SeedConstructorArguments.Select(SeedArgument))}){RequiredMemberInitializer(plan)}";

        sb.AppendLine();
        sb.Append(indent).Append("    public static ").Append(typeName)
          .AppendLine(
              " Rehydrate(global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Array> columns, int rowIndex)");
        sb.Append(indent).AppendLine("    {");
        sb.Append(indent).Append("        var __result = ").Append(initExpression).AppendLine(";");

        foreach (var field in plan.Fields)
        {
            sb.Append(indent)
              .Append("        if (columns.TryGetValue(\"").Append(field.PropertyName)
              .Append("\", out var __").Append(field.PropertyName).AppendLine("))");
            sb.Append(indent)
              .Append("            __result = __result with { ")
              .Append(IdentifierEscaper.Escape(field.PropertyName)).Append(" = ((")
              .Append(field.ClrArrayTypeName)
              .Append(")__").Append(field.PropertyName).Append(")[rowIndex] };");
            sb.AppendLine();
        }

        sb.Append(indent).AppendLine("        return __result;");
        sb.Append(indent).AppendLine("    }");
    }

    // Emits
    //   public static IComparer<TSelf> CreateColumnSortComparer(ColumnSortSpec spec)
    //   private sealed class __ColumnSortComparer : IComparer<TSelf>
    //
    // The segment-format hot path resolves this method once via cached reflection
    // (ColumnSortComparerFactory<TSelf>) and uses the strongly-typed Comparer<T>.Default chain
    // for every Array.Sort comparison — replacing the legacy compiled-lambda + reflection
    // accessor pattern.
    private static void AppendCreateColumnSortComparer(
        StringBuilder sb,
        ColumnarSourceGenerator.ColumnarTypePlan plan,
        string indent)
    {
        // Reference-type emission must annotate IComparer<T>'s Compare parameters as nullable
        // to satisfy the interface signature exactly (CS8767 fires otherwise under
        // TreatWarningsAsErrors). Value-type emission omits the annotation since `T?` collapses
        // to `T` for non-nullable structs but the BCL surfaces the parameter without the nullable
        // suffix on value types.
        var typeName = IdentifierEscaper.Escape(plan.Name);
        var isReferenceType = plan.TypeKeyword is "class" or "record";
        var compareParam = isReferenceType ? typeName + "?" : typeName;
        // Reference-type compare passes the nullable parameters into a Comparison<T> that takes
        // non-nullable T. The legacy reflection comparator never tolerated null records either —
        // dereferencing here keeps that contract while satisfying the IComparer<T>.Compare
        // signature exactly. Inside the static lambdas, parameters are already non-nullable.
        var bangAtCallSite = isReferenceType ? "!" : string.Empty;

        sb.AppendLine();
        sb.Append(indent).AppendLine("    /// <summary>");
        sb.Append(indent).AppendLine("    /// Source-generator-emitted factory for an <see cref=\"global::System.Collections.Generic.IComparer{T}\"/>");
        sb.Append(indent).Append("    /// over <see cref=\"").Append(plan.Name).AppendLine("\"/> driven by a <see cref=\"global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.ColumnSortSpec\"/>.");
        sb.Append(indent).AppendLine("    /// Replaces the reflection-based comparator on the columnar sort path: every comparison");
        sb.Append(indent).AppendLine("    /// dispatches to a strongly-typed <see cref=\"global::System.Collections.Generic.Comparer{T}\"/>");
        sb.Append(indent).AppendLine("    /// chain selected at construction time, so per-element cost is one delegate invocation");
        sb.Append(indent).AppendLine("    /// instead of one <see cref=\"global::System.Reflection.PropertyInfo.GetValue(object?)\"/> +");
        sb.Append(indent).AppendLine("    /// boxing + virtual-call <c>CompareTo</c> per sort column.");
        sb.Append(indent).AppendLine("    /// </summary>");
        sb.Append(indent).AppendLine("    /// <exception cref=\"global::System.ArgumentNullException\"><paramref name=\"spec\"/> is <see langword=\"null\"/>.</exception>");
        sb.Append(indent).AppendLine("    /// <exception cref=\"global::System.ArgumentOutOfRangeException\">A spec entry declares an undefined <see cref=\"global::Boutquin.Storage.Domain.Enums.SortDirection\"/> value.</exception>");
        sb.Append(indent).AppendLine("    /// <exception cref=\"global::System.ArgumentException\">A spec entry names a property that is not a sortable scalar on this type.</exception>");
        sb.Append(indent).Append("    public static global::System.Collections.Generic.IComparer<")
          .Append(typeName).AppendLine("> CreateColumnSortComparer(");
        sb.Append(indent).AppendLine("        global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.ColumnSortSpec spec)");
        sb.Append(indent).AppendLine("    {");
        sb.Append(indent).AppendLine("        if (spec is null) throw new global::System.ArgumentNullException(nameof(spec));");
        sb.Append(indent).AppendLine("        return new __ColumnSortComparer(spec);");
        sb.Append(indent).AppendLine("    }");
        sb.AppendLine();

        sb.Append(indent).Append("    private sealed class __ColumnSortComparer : global::System.Collections.Generic.IComparer<")
          .Append(typeName).AppendLine(">");
        sb.Append(indent).AppendLine("    {");
        sb.Append(indent).Append("        private readonly global::System.Comparison<")
          .Append(typeName).AppendLine(">[] _comparers;");
        sb.AppendLine();

        sb.Append(indent).AppendLine("        public __ColumnSortComparer(global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.ColumnSortSpec spec)");
        sb.Append(indent).AppendLine("        {");
        sb.Append(indent).AppendLine("            var __cols = spec.Columns;");
        sb.Append(indent).Append("            _comparers = new global::System.Comparison<")
          .Append(typeName).AppendLine(">[__cols.Count];");
        sb.Append(indent).AppendLine("            for (var __i = 0; __i < __cols.Count; __i++)");
        sb.Append(indent).AppendLine("            {");
        sb.Append(indent).AppendLine("                var __name = __cols[__i].Name;");
        sb.Append(indent).AppendLine("                var __dir = __cols[__i].Direction;");
        sb.Append(indent).AppendLine("                if (__dir != global::Boutquin.Storage.Domain.Enums.SortDirection.Ascending");
        sb.Append(indent).AppendLine("                    && __dir != global::Boutquin.Storage.Domain.Enums.SortDirection.Descending)");
        sb.Append(indent).AppendLine("                {");
        sb.Append(indent).AppendLine("                    throw new global::System.ArgumentOutOfRangeException(");
        sb.Append(indent).AppendLine("                        nameof(spec),");
        sb.Append(indent).AppendLine("                        \"ColumnSortSpec entry at index \"");
        sb.Append(indent).AppendLine("                            + __i.ToString(global::System.Globalization.CultureInfo.InvariantCulture)");
        sb.Append(indent).AppendLine("                            + \" declares undefined SortDirection value \" + __dir.ToString()");
        sb.Append(indent).AppendLine("                            + \".\");");
        sb.Append(indent).AppendLine("                }");
        sb.Append(indent).Append("                global::System.Comparison<")
          .Append(typeName).AppendLine("> __base = __name switch");
        sb.Append(indent).AppendLine("                {");
        foreach (var prop in plan.SortableProperties)
        {
            // String columns compare ordinally: Comparer<string>.Default resolves to
            // culture-sensitive string.CompareTo, which would make on-disk row order depend
            // on the writing machine's locale. The columnar stack is ordinal everywhere else
            // (ZoneMapComputer min/max uses string.CompareOrdinal); the physical sort must match.
            // The switch-case label is a STRING literal (matches __name at runtime) → bare name.
            // The a./b. member accesses are IDENTIFIER positions → escaped.
            var member = IdentifierEscaper.Escape(prop.PropertyName);
            if (prop.ClrPropertyTypeName == "string")
            {
                sb.Append(indent).Append("                    \"").Append(prop.PropertyName)
                  .Append("\" => static (a, b) => string.CompareOrdinal(a.")
                  .Append(member).Append(", b.")
                  .Append(member).AppendLine("),");
                continue;
            }

            sb.Append(indent).Append("                    \"").Append(prop.PropertyName)
              .Append("\" => static (a, b) => global::System.Collections.Generic.Comparer<")
              .Append(prop.ClrPropertyTypeName).Append(">.Default.Compare(a.")
              .Append(member).Append(", b.")
              .Append(member).AppendLine("),");
        }
        sb.Append(indent).AppendLine("                    _ => throw new global::System.ArgumentException(");
        sb.Append(indent).Append("                        \"ColumnSortSpec column '\" + __name + \"' does not match any sortable public property on ")
          .Append(plan.Name).AppendLine(".\",");
        sb.Append(indent).AppendLine("                        nameof(spec)),");
        sb.Append(indent).AppendLine("                };");
        sb.Append(indent).AppendLine("                // Descending inverts by swapping arguments — never by negating, which");
        sb.Append(indent).AppendLine("                // would overflow on int.MinValue comparison results.");
        sb.Append(indent).AppendLine("                _comparers[__i] = __dir == global::Boutquin.Storage.Domain.Enums.SortDirection.Descending");
        sb.Append(indent).AppendLine("                    ? (a, b) => __base(b, a)");
        sb.Append(indent).AppendLine("                    : __base;");
        sb.Append(indent).AppendLine("            }");
        sb.Append(indent).AppendLine("        }");
        sb.AppendLine();

        sb.Append(indent).Append("        public int Compare(")
          .Append(compareParam).Append(" x, ").Append(compareParam).AppendLine(" y)");
        sb.Append(indent).AppendLine("        {");
        sb.Append(indent).AppendLine("            for (var __i = 0; __i < _comparers.Length; __i++)");
        sb.Append(indent).AppendLine("            {");
        sb.Append(indent).Append("                var __cmp = _comparers[__i](x").Append(bangAtCallSite)
          .Append(", y").Append(bangAtCallSite).AppendLine(");");
        sb.Append(indent).AppendLine("                if (__cmp != 0) return __cmp;");
        sb.Append(indent).AppendLine("            }");
        sb.Append(indent).AppendLine("            return 0;");
        sb.Append(indent).AppendLine("        }");
        sb.Append(indent).AppendLine("    }");
    }

    private static void AppendProjectTo(StringBuilder sb, ColumnarSourceGenerator.ColumnarTypePlan plan, string indent)
    {
        var typeName = IdentifierEscaper.Escape(plan.Name);
        var isRecordStruct = plan.TypeKeyword == "record struct";

        // A record class without a parameterless constructor (a positional record) is seeded by
        // cloning the receiver with every column clipped to default — no constructor is named,
        // as in ProjectionEmitter on the row path.
        var initExpression = isRecordStruct
            ? $"default({typeName})"
            : plan.HasParameterlessConstructor
                ? $"new {typeName}(){RequiredMemberInitializer(plan)}"
                : plan.Fields.Length == 0
                    ? "this with { }"
                    : $"this with {{ {string.Join(", ", plan.Fields.Select(f => IdentifierEscaper.Escape(f.PropertyName) + " = default!"))} }}";

        sb.AppendLine();
        sb.Append(indent).Append("    public ").Append(typeName)
          .AppendLine(" ProjectTo(global::Boutquin.Storage.Domain.ValueObjects.TimeSeries.Columnar.ColumnProjection projection)");
        sb.Append(indent).AppendLine("    {");
        sb.Append(indent).AppendLine("        if (projection.FieldNames.Count == 0) return this;");
        sb.AppendLine();

        sb.Append(indent).Append("        var __declared = new string[] { ");
        var __first = true;
        foreach (var field in plan.Fields)
        {
            if (!__first)
            {
                sb.Append(", ");
            }
            sb.Append('"').Append(field.PropertyName).Append('"');
            __first = false;
        }
        sb.AppendLine(" };");

        sb.Append(indent).Append("        var __result = ").Append(initExpression).AppendLine(";");
        sb.Append(indent).AppendLine("        foreach (var __name in projection.FieldNames)");
        sb.Append(indent).AppendLine("        {");
        sb.Append(indent).AppendLine("            switch (__name)");
        sb.Append(indent).AppendLine("            {");
        foreach (var field in plan.Fields)
        {
            // Case label is a STRING literal → bare; the `with` member + `this.` access are
            // IDENTIFIER positions → escaped.
            var member = IdentifierEscaper.Escape(field.PropertyName);
            sb.Append(indent).Append("                case \"").Append(field.PropertyName).AppendLine("\":");
            sb.Append(indent).Append("                    __result = __result with { ")
              .Append(member).Append(" = this.").Append(member).AppendLine(" };");
            sb.Append(indent).AppendLine("                    break;");
        }
        sb.Append(indent).AppendLine("                default:");
        sb.Append(indent).AppendLine("                    if (!projection.AllowMissing)");
        sb.Append(indent).AppendLine("                    {");
        sb.Append(indent).AppendLine("                        throw new global::Boutquin.Storage.Domain.Exceptions.ColumnNotFoundException(__name, 1u, __declared);");
        sb.Append(indent).AppendLine("                    }");
        sb.Append(indent).AppendLine("                    break;");
        sb.Append(indent).AppendLine("            }");
        sb.Append(indent).AppendLine("        }");
        sb.Append(indent).AppendLine("        return __result;");
        sb.Append(indent).AppendLine("    }");
    }
}
